// "Договор" (интерфейс) для всего, с чем можно взаимодействовать на кнопку E.
// Дверь, выключатель, предмет — каждый сам решает, ЧТО делать при нажатии.
// Благодаря этому PlayerInteraction не нужно знать про каждый тип объекта отдельно.
public interface IInteractable
{
    // Текст подсказки на экране, например "Открыть дверь"
    string GetPrompt();

    // Что происходит при нажатии E
    void Interact(PlayerInteraction player);
}
